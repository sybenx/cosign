import { writeFileSync } from 'node:fs';
import { generateSecretKey, getPublicKey, verifyEvent } from 'nostr-tools/pure';
import { BunkerSigner, createNostrConnectURI } from 'nostr-tools/nip46';
import { bytesToHex, randomBytes } from '@noble/hashes/utils.js';
const clientSk = generateSecretKey();
const uri = createNostrConnectURI({ clientPubkey: getPublicKey(clientSk), relays: ['wss://relay.primal.net'], secret: bytesToHex(randomBytes(8)), name: 'Emulator site', url: 'https://emu.test' });
writeFileSync(process.argv[2], uri);
const signer = await BunkerSigner.fromURI(clientSk, uri, {}, 120_000);
const ev = await signer.signEvent({ kind: 1, created_at: Math.floor(Date.now() / 1000), content: 'after report lost', tags: [] });
console.log('note', verifyEvent(ev));
process.exit(0);
