// Behaviour vectors from the reference implementation (vectors.md cases 3, 5, 6, 7, 12), as data, so a
// second implementation (Kotlin) can run the same cases: inputs are signed events and approvals,
// outputs are what src/ computes. Run: node vectors/gen-behaviour.ts > vectors/behaviour.json
import { fixture } from '../test/helpers.ts';
import { checkEpochRecord } from '../src/record.ts';
import { computeMembership } from '../src/membership.ts';
import { approveLock, approvePair, approvePaper, checkApproval } from '../src/approval.ts';
import { checkAssertion, softLock, FLAGS } from '../src/lock.ts';
import { what } from '../src/codes.ts';
import { deal as dealRedeal } from '../src/redeal.ts';
import { newKey } from '../src/event.ts';
import { KeykinError } from '../src/bytes.ts';
import type { Change } from '../src/types.ts';

const EXP = 1_900_000_000;
const code = (f: () => unknown) => { try { f(); return 'ok'; } catch (e: any) { return e instanceof KeykinError ? e.code : 'error'; } };
const F = fixture();
const A = F.devices[0];
const out: any = { note: 'Generated by keykin/vectors/gen-behaviour.ts from the TypeScript reference. Keys are random per run; every case is self-contained.', g: F.g, epoch_id: F.epochId, record: F.recEv, cases: {} };

// --- case 3: epoch records ------------------------------------------------------------------
out.cases.records = [
  { name: 'valid', event: F.recEv, expect: code(() => checkEpochRecord(F.recEv, { g: F.g })) },
  { name: 'kind 1 lookalike', event: F.sign(1, F.recEv.content, F.recEv.tags), expect: code(() => checkEpochRecord(F.sign(1, F.recEv.content, F.recEv.tags), { g: F.g })) },
  ...(() => { const e = F.sign(30242, F.recEv.content, [['d', 'keykin'], ['v', '1'], ['epoch', '2']]); return [{ name: 'tags disagree', event: e, expect: code(() => checkEpochRecord(e, { g: F.g })) }]; })(),
  ...(() => { const e = F.sign(30242, F.recEv.content, [['d', 'cosign'], ['v', '1'], ['epoch', '1']]); return [{ name: 'old d tag', event: e, expect: code(() => checkEpochRecord(e, { g: F.g })) }]; })(),
  ...(() => { const e = { ...F.recEv, content: F.recEv.content.replace('"t":4', '"t":3') }; return [{ name: 'tampered', event: e, expect: code(() => checkEpochRecord(e, { g: F.g })) }]; })(),
];

// --- cases 5/6/7/12: membership from sets of changes ---------------------------------------
const add = (key: string, lock: any = null, salt = 0) => { const l: Change[] = [{ add: { key, kind: 'device', lock, salt } }]; return F.change(l[0], l, approveLock(F.g, F.epochId, l, EXP, A.kp.pub, A.lock!)); };
const listEvs = (list: Change[], ap: any, paperTo = F.backup.kp.pub) => {
  const d = dealRedeal(F.g, A.kp, [], new Map(), paperTo, [5, 6]);
  return list.map((c) => F.change('redeal' in c ? { redeal: d.redeal } : c, list, ap));
};
const B = newKey(), C = newKey();
const view = (evs: any[]) => {
  const m = computeMembership(F.rec, evs);
  return { devices: [...m.devices].sort(), removed: [...m.removed].sort(), seats: Object.fromEntries([...m.seats].map(([k, s]) => [k, s.holder?.key ?? null])),
    backup: m.backupKey, refused: m.refused.map((x) => x.code).sort(), invariant: m.invariantError !== null };
};
const rmList: Change[] = [{ remove: B.pub }, { redeal: { dealer: A.kp.pub } }];
const rm = listEvs(rmList, approveLock(F.g, F.epochId, rmList, EXP, A.kp.pub, A.lock!));
const y = { key: newKey().pub, kind: 'server', shares: [8], host: newKey().pub };
const seatList: Change[] = [{ seat: { seat: 'server:8', new: y, replaces: F.servers[2].kp.pub } }, { redeal: { dealer: A.kp.pub } }];
const seat = listEvs(seatList, approveLock(F.g, F.epochId, seatList, EXP, A.kp.pub, A.lock!));
const helperApprover = newKey();
const badAdd = (() => { const l: Change[] = [{ add: { key: C.pub, kind: 'device', lock: null, salt: 0 } }]; return F.change(l[0], l, approvePair(F.g, F.epochId, l, EXP, A.kp, helperApprover, 'aa'.repeat(16))); })();
const addB = add(B.pub);
out.cases.membership = [
  { name: 'add by lock', changes: [addB], expect: view([addB]) },
  { name: 'add then [remove, redeal], any order', changes: [...rm, addB], expect: view([addB, ...rm]) },
  { name: 'remove without its redeal waits (list incomplete)', changes: [addB, rm[0]], expect: view([addB, rm[0]]) },
  { name: 'pair with a non-device approver is refused', changes: [badAdd], expect: view([badAdd]) },
  { name: 'same key, two salts: void', changes: [add(C.pub, null, 0), add(C.pub, null, 1)], expect: null as any },
  { name: 'seat replaced', changes: seat, expect: view(seat) },
];
out.cases.membership[4].expect = view(out.cases.membership[4].changes);
// Lock chains: two lock changes replacing one lock are both void; same new counts once.
const lockEv = (pub: any, replaces: string) => { const l: Change[] = [{ lock: { member: A.kp.pub, replaces, new: pub } }]; return F.change(l[0], l, approvePair(F.g, F.epochId, l, EXP, A.kp, B, 'ee'.repeat(16))); };
const nl1 = softLock().pub, nl2 = softLock().pub;
const lv = (evs: any[]) => ({ ...view(evs), locks: Object.fromEntries([...computeMembership(F.rec, evs).locks].map(([k, l]) => [k, l?.pub ?? null])) });
out.cases.membership.push(
  { name: 'two lock changes for one lock: both void', changes: [addB, lockEv(nl1, A.lock!.pub.pub), lockEv(nl2, A.lock!.pub.pub)], expect: null },
  { name: 'two lock changes with the same new lock: one', changes: [addB, lockEv(nl1, A.lock!.pub.pub), lockEv(nl1, A.lock!.pub.pub)], expect: null },
);
for (const c of out.cases.membership.slice(-2)) c.expect = lv(c.changes);
// Seats: same new counts once; different new voids both; one host in two seats within 24 hours voids both.
const seatEvsX = (idx: number, replaces: string | null, entry: any, expiry = EXP) => { const l: Change[] = [{ seat: { seat: `server:${idx}`, new: entry, replaces } }, { redeal: { dealer: A.kp.pub } }];
  return listEvs(l, approveLock(F.g, F.epochId, l, expiry, A.kp.pub, A.lock!)); };
const z1 = { key: newKey().pub, kind: 'server', shares: [8], host: newKey().pub }, z2 = { key: newKey().pub, kind: 'server', shares: [8], host: newKey().pub };
const hh = newKey().pub;
const two = [...seatEvsX(4, F.servers[0].kp.pub, { key: newKey().pub, kind: 'server', shares: [4], host: hh }), ...seatEvsX(7, F.servers[1].kp.pub, { key: newKey().pub, kind: 'server', shares: [7], host: hh })];
const apart = [...seatEvsX(4, F.servers[0].kp.pub, { key: newKey().pub, kind: 'server', shares: [4], host: hh }), ...seatEvsX(7, F.servers[1].kp.pub, { key: newKey().pub, kind: 'server', shares: [7], host: hh }, EXP + 3 * 86400)];
const twin = seatEvsX(8, F.servers[2].kp.pub, z1), twin2 = seatEvsX(8, F.servers[2].kp.pub, z1), other = seatEvsX(8, F.servers[2].kp.pub, z2);
out.cases.membership.push(
  { name: 'seat: same new twice counts once', changes: [...twin, ...twin2], expect: view([...twin, ...twin2]) },
  { name: 'seat: different new voids both', changes: [...twin, ...other], expect: view([...twin, ...other]) },
  { name: 'one host in two seats, approved within 24 hours: both void', changes: two, expect: view(two) },
  { name: 'one host in two seats, approved days apart: not void, but the view breaks I2 (adopters refuse it)', changes: apart, expect: view(apart) },
);
// Papers: the lowest list hash wins; the loser's key is removed.
const paperEvs = () => { const K = newKey(); const l: Change[] = [{ paper: { key: K.pub, replaces: F.backup.kp.pub } }, { redeal: { dealer: A.kp.pub } }];
  const a = approveLock(F.g, F.epochId, l, EXP, A.kp.pub, A.lock!); const d = dealRedeal(F.g, A.kp, [], new Map(), K.pub, [5, 6]);
  return [F.change({ paper: { key: K.pub, replaces: F.backup.kp.pub, inner: 'aa'.repeat(32), state: [] } }, l, a), F.change({ redeal: d.redeal }, l, a)]; };
const pp = [...paperEvs(), ...paperEvs()];
out.cases.membership.push({ name: 'two papers: lowest hash wins', changes: pp, expect: view(pp) });

// --- case 5: lock assertions ---------------------------------------------------------------
const L = A.lock!, ev = 'ab'.repeat(32);
out.cases.locks = [
  { name: 'sign', lock: L.pub, what: Buffer.from(what.sign(ev)).toString('hex'), assertion: L.assert(F.g, what.sign(ev)), expect: null },
  { name: 'UV missing', lock: L.pub, what: Buffer.from(what.sign(ev)).toString('hex'), assertion: L.assert(F.g, what.sign(ev), FLAGS.UP), expect: 'lock_flags' },
  { name: 'other body', lock: L.pub, what: Buffer.from(what.sign(ev)).toString('hex'), assertion: L.assert(F.g, what.cancel(ev)), expect: 'lock_challenge' },
  { name: 'wrong key', lock: softLock().pub, what: Buffer.from(what.sign(ev)).toString('hex'), assertion: L.assert(F.g, what.sign(ev)), expect: 'lock_sig' },
];
for (const c of out.cases.locks) if (checkAssertion(F.g, c.lock, Buffer.from(c.what, 'hex'), c.assertion) !== c.expect) throw new Error(`lock case ${c.name}`);

// --- case 6: approvals against a membership ------------------------------------------------
const auth = computeMembership(F.rec, [addB]).authority;
const addX: Change[] = [{ add: { key: newKey().pub, kind: 'device', lock: null, salt: 0 } }];
const lockCh: Change[] = [{ lock: { member: A.kp.pub, replaces: A.lock!.pub.pub, new: softLock().pub } }];
const ap = (list: Change[], a: any, name: string) => ({ name, changes: [addB], list, approval: a, expect: checkApproval(auth, list, a).error });
out.cases.approvals = [
  ap(addX, approveLock(F.g, F.epochId, addX, EXP, A.kp.pub, A.lock!), 'add by lock'),
  ap(addX, approvePair(F.g, F.epochId, addX, EXP, A.kp, B, 'bb'.repeat(16)), 'add by pair'),
  ap(lockCh, approveLock(F.g, F.epochId, lockCh, EXP, A.kp.pub, A.lock!), 'lock change by lock: not allowed'),
  ap(rmList, approvePair(F.g, F.epochId, rmList, EXP, A.kp, A.kp, 'cc'.repeat(16)), 'pair with one device twice'),
  ap(addX, approvePaper(F.g, F.epochId, addX, EXP, A.kp, F.backup.kp, 'dd'.repeat(16), F.servers[0].host.pub), 'add by paper'),
  ap(addX, approvePaper(F.g, F.epochId, addX, EXP, A.kp, newKey(), 'dd'.repeat(16), F.servers[0].host.pub), 'paper by a stranger key'),
];
// self (§4.6) and recovery (§6.2) approvals.
{
  const { approveSelf, approveRecovery, signWaited } = await import('../src/approval.ts');
  const { recoveryWaitId } = await import('../src/codes.ts');
  const selfL: Change[] = [{ remove: A.kp.pub, to: B.pub }, { redeal: { dealer: B.pub } }];
  out.cases.approvals.push(ap(selfL, approveSelf(F.g, selfL, A.kp, B), 'self remove, countersigned by the app'));
  out.cases.approvals.push(ap(selfL, approveSelf(F.g, selfL, A.kp, newKey()), 'self remove, wrong app signature'));
  const r = 'ab'.repeat(16), wait = recoveryWaitId(F.backup.kp.pub, F.epochId, r);
  const w = (k: number, len = 3 * 86400) => signWaited(F.g, F.servers[k].host, 'recovery', wait, 1_800_000_000, 1_800_000_000 + len);
  out.cases.approvals.push(ap(addX, approveRecovery(F.g, addX, F.backup.kp, { r }, [w(0), w(1)]), 'recovery with two waited statements'));
  out.cases.approvals.push(ap(addX, approveRecovery(F.g, addX, F.backup.kp, { r }, [w(0), w(0)]), 'recovery: one server twice'));
  out.cases.approvals.push(ap(addX, approveRecovery(F.g, addX, F.backup.kp, { r }, [w(0), w(1, 86400)]), 'recovery: a wait shorter than W'));
}
console.log(JSON.stringify(out, null, 1));
